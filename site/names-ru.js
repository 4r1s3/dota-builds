// Текст, набранный на русской раскладке вместо английской: «шщ» → «io»
const RU_LAYOUT = "йцукенгшщзхъфывапролджэячсмитьбю";
const EN_LAYOUT = "qwertyuiop[]asdfghjkl;'zxcvbnm,.";
function fromRuLayout(s) {
  return [...s].map(c => {
    const i = RU_LAYOUT.indexOf(c);
    return i >= 0 ? EN_LAYOUT[i] : c;
  }).join("");
}
